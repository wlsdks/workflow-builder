/** 명사 + 접미 → 동사가 되는 패턴. 사전에 없는 명사도 잡는다 */
export const RE_VERBALIZER =
  /[가-힣]{2,}(?:하다|한다|해요|합니다|했|하고|하며|하여|해서|하기|함|해|시키|되다|된다|돼요|됩니다|되고|되어|돼서|됨)/;

/** 순수 동사 + 활용 어미 */
export const RE_PLAIN_VERB_INFLECTED = new RegExp(
  `(?:${PLAIN_VERBS.join('|')})(?:아|어|여|고|며|면서|서|는|은|을|기|지|자|다|어요|아요|여요|습니다|ㅂ니다|세요|십시오|주세요|줘요|어라|아라|았|었)`,
);

/** 명사형 종결 (§4.5 `noun` 문체) */
export const RE_NOUN_ENDING = /(?:[가-힣](?:함|됨|임|음)|하기|할\s?것|요망|필요|바람|요함)$/;

/** 명사형으로 끝나는 PPT 도형 텍스트 (§2.2 RE_NOUN_END) */
export const RE_NOUN_END =
  /(?:[가-힣]{2,}(?:등록|접수|확인|발송|검토|승인|정리|입력|작성|보고|취합|마감|완료|처리|요청|전달|조회|발행|점검)|[가-힣]+(?:화|서|표|안|건))\s*$/;

const RE_ACTION_NOUN = new RegExp(`(?:${ACTION_VERBS.join('|')})(?:\\s*(?:을|를|은|는|이|가))?\\s*$`);

/**
 * 공손·평서 종결 어미로 끝나면 그 절에는 서술어가 있다.
 * (`"기다립니다"`처럼 어간이 사전에 없어도 문장이 끝났다는 사실은 표면형이 말해준다)
 */
const RE_POLITE_END = /[가-힣](?:습니다|ㅂ니다|립니다|합니다|해요|어요|아요|여요|세요|십시오|는다|ㄴ다|한다|해|돼요|예요|이에요|에요)[.!?…]*$/;

/**
 * 이 절에 "동작"이 있는가.
 *
 * §3.6 채점의 `+0.15 (양쪽에 서술어)`와 §8.3·§8.4 노이즈 감지기의 본문 보호 가드가
 * 전부 이 한 함수를 부른다. 여기가 헐거우면 서명 탐색이 본문을 먹는다.
 */
export function hasActionPredicate(clause: string): boolean {
  const t = clause.trim();
  if (!t) return false;
  if (RE_VERBALIZER.test(t)) return true;
  if (RE_PLAIN_VERB_INFLECTED.test(t)) return true;
  if (RE_NOUN_ENDING.test(t)) return true;
  if (RE_POLITE_END.test(t)) return true;
  return RE_ACTION_NOUN.test(t.replace(/[)\]}」』.!?…]+$/, ''));
}

/**
 * 문장의 마지막 서술어 구를 잘라낸다 (뒤에서 앞으로 최대 20자) — §5.3.
 *
 * `"여신한도는 재무팀 승인 후 입력할 것"` 은 `승인`을 포함하지만 **하는 일은 입력**이다.
 * 이걸 hold로 찍으면 흐름이 통째로 멈춘 것처럼 그려진다.
 */
export function mainPredicate(t: string): string {
  const s = t.trim().replace(/[.!?…]+$/, '');
  const m = /(?:[가-힣]{1,12}(?:합니다|습니다|해요|어요|아요|한다|는다|하기|할\s?것|함|됨|하세요|하시면|하고|해서))\s*$/.exec(s);
  return m ? m[0] : s.slice(-20);
}

/* ── 문체 (§4.5) ───────────────────────────────────────────────────────────── */

export type Style = 'haeyo' | 'hamnida' | 'plain' | 'noun';

const STYLE_RE: readonly [Style, RegExp][] = [
  ['hamnida', /(?:합니다|습니다|ㅂ니다|십시오|세요)[.!?]?$/],
  ['haeyo', /(?:해요|어요|아요|예요|이에요|돼요|봐요|줘요)[.!?]?$/],
  ['plain', /(?:[가-힣](?:는다|ㄴ다|다))[.]?$/],
  ['noun', /(?:[가-힣](?:함|됨|임|음)|하기|할\s?것|요망|필요|바람|요함)$/],
];

export function detectStyle(t: string): Style | null {
  const s = t.trim();
  for (const [style, re] of STYLE_RE) if (re.test(s)) return style;
  return null;
}

/**
 * 문체는 통일하지 않는다 (§4.5). 이 함수는 **절 분할로 잘려서 연결어미로 끝나버린
 * 제목**을 어느 문체로 맞출지 고를 때만 쓰인다.
 */
export function dominantStyle(items: readonly string[]): Style {
  const c: Record<Style, number> = { haeyo: 0, hamnida: 0, plain: 0, noun: 0 };
  for (const t of items) {
    const s = detectStyle(t);
    if (s) c[s]++;
  }
  const top = (Object.entries(c) as [Style, number][]).sort((a, b) => b[1] - a[1])[0]!;
  return top[1] === 0 ? 'haeyo' : top[0]; // 기본값은 제품 톤과 같은 해요체
}
